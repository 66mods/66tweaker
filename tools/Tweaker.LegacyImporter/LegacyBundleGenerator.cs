using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Tweaker.Domain.Legacy;

namespace Tweaker.LegacyImporter;

internal static class LegacyBundleGenerator
{
    private static readonly string[] FixturePaths =
    [
        "66mods Tweaks v40012(RUN AS ADMIN).bat",
        "Fixes/Fix Disabled WiFi (RUN AS ADMIN).bat",
        "Fixes/Fix Fortnite Not Starting (RUN AS ADMIN).bat"
    ];

    public static void Write(string sourceRoot, string jsonOutput, string sourceOutput)
    {
        var root = Path.GetFullPath(sourceRoot);
        _ = Program.ValidateExistingPathWithoutReparsePoints(root);
        var parser = new LegacyBatParser();
        var sourceLines = new List<LegacySourceLine>();
        var originalByFingerprint = new Dictionary<string, string>(StringComparer.Ordinal);
        var hashes = new List<SourceHash>();

        foreach (var relative in FixturePaths)
        {
            var path = Path.GetFullPath(Path.Combine(root, relative.Replace('/', Path.DirectorySeparatorChar)));
            Program.EnsureContained(root, path, "Fixture path");
            var bytes = File.ReadAllBytes(path);
            if (bytes.Length > LegacyBatParser.MaximumInputCharacters)
                throw new InvalidDataException($"Frozen fixture is too large: {relative}");
            hashes.Add(new(relative, bytes.LongLength, Convert.ToHexString(SHA256.HashData(bytes))));
            var parsed = parser.Parse(relative, Encoding.Latin1.GetString(bytes));
            sourceLines.AddRange(parsed);
            foreach (var line in parsed) originalByFingerprint.Add(line.Fingerprint, line.OriginalText.Trim());
        }

        var effects = sourceLines.GroupBy(x => x.NormalizedText, StringComparer.Ordinal)
            .Select((group, index) => CreateEffect(index, group.ToArray(), originalByFingerprint))
            .ToArray();
        if (sourceLines.Count != 1917 || effects.Length != 1500)
            throw new InvalidDataException($"Frozen coverage changed: {sourceLines.Count}/1917 source, {effects.Length}/1500 canonical.");

        var document = new BundleDocument(1, sourceLines.Count, effects.Length, hashes, effects);
        var json = JsonSerializer.SerializeToUtf8Bytes(document,
            new JsonSerializerOptions(JsonSerializerDefaults.Web) { WriteIndented = false });
        var bundleHash = Convert.ToHexString(SHA256.HashData(json));
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(jsonOutput))!);
        File.WriteAllBytes(jsonOutput, json);
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(sourceOutput))!);
        var generated = $$"""
// <auto-generated />
namespace Tweaker.Infrastructure.Windows.Legacy;

internal static class LegacyBundleIdentity
{
    internal const int SchemaVersion = 1;
    internal const int SourceFingerprintCount = 1917;
    internal const int CanonicalEffectCount = 1500;
    internal const string Sha256 = "{{bundleHash}}";
}
""";
        File.WriteAllText(sourceOutput, generated + Environment.NewLine, new UTF8Encoding(false));
        Console.WriteLine($"Generated {sourceLines.Count} source fingerprints -> {effects.Length} canonical effects; excluded={effects.Count(x => !x.Executable)}; sha256={bundleHash}");
    }

    private static BundleEffect CreateEffect(int index, IReadOnlyList<LegacySourceLine> lines,
        IReadOnlyDictionary<string, string> originalByFingerprint)
    {
        var canonical = lines[0];
        var command = originalByFingerprint[canonical.Fingerprint];
        var resolution = command.Contains("UseBestResolution", StringComparison.OrdinalIgnoreCase) ||
            command.Contains("SmoothResolutionEnabled", StringComparison.OrdinalIgnoreCase) ||
            command.Contains("resolution", StringComparison.OrdinalIgnoreCase) && command.Contains("display", StringComparison.OrdinalIgnoreCase);
        var irreversible = canonical.Kind is LegacyCommandKind.FileDeletion or LegacyCommandKind.RegistryDelete ||
            command.Contains("Remove-AppxPackage", StringComparison.OrdinalIgnoreCase) ||
            command.Contains("Remove-Item", StringComparison.OrdinalIgnoreCase) ||
            command.Contains(" sc delete ", StringComparison.OrdinalIgnoreCase) ||
            command.Contains("/delete", StringComparison.OrdinalIgnoreCase);
        var securityReduction = command.Contains("Set-ProcessMitigation", StringComparison.OrdinalIgnoreCase) ||
            command.Contains("Disable-WindowsOptionalFeature", StringComparison.OrdinalIgnoreCase) ||
            command.Contains("EnableLUA", StringComparison.OrdinalIgnoreCase) ||
            command.Contains("SmartScreen", StringComparison.OrdinalIgnoreCase) ||
            command.Contains("Defender", StringComparison.OrdinalIgnoreCase);
        var section = canonical.Section.ToLowerInvariant();
        var gaming = IsGaming(section) || canonical.Kind is LegacyCommandKind.PowerCfg or LegacyCommandKind.Netsh;
        var safe = canonical.Kind is LegacyCommandKind.RegistryAdd &&
            (section is "animations" or "keyboard" or "mouse" or "realinputdelay") &&
            command.Contains("HKCU", StringComparison.OrdinalIgnoreCase);
        var maximum = !irreversible && !securityReduction && canonical.Kind != LegacyCommandKind.FileDeletion;
        var profiles = new List<string>();
        if (!resolution)
        {
            if (safe) profiles.Add("safe");
            if (gaming || safe) profiles.Add("gaming");
            if (maximum) profiles.Add("maximum");
            profiles.Add("full");
        }
        return new($"legacy-{index + 1:D4}", canonical.Fingerprint, lines.Select(x => x.Fingerprint).ToArray(),
            canonical.SourceFile, canonical.LineNumber, canonical.Section, canonical.Kind.ToString(), command,
            profiles, !resolution, resolution ? "Output-resolution changes are excluded by product policy." : null,
            irreversible, securityReduction);
    }

    private static bool IsGaming(string section) => section is
        "fortnite" or "valorant" or "gta5" or "minecraft" or "directx" or "mouse" or "keyboard" or
        "realinputdelay" or "internet" or "lowerping" or "power" or "amd" or "nvidia" or "intel" or
        "amdcpu" or "intelcpu";

    private sealed record SourceHash(string Path, long Bytes, string Sha256);
    private sealed record BundleEffect(string Id, string CanonicalFingerprint, IReadOnlyList<string> SourceFingerprints,
        string SourceFile, int LineNumber, string Section, string Kind, string Command,
        IReadOnlyList<string> Profiles, bool Executable, string? SkipReason, bool Irreversible, bool SecurityReduction);
    private sealed record BundleDocument(int SchemaVersion, int SourceFingerprintCount, int CanonicalEffectCount,
        IReadOnlyList<SourceHash> Sources, IReadOnlyList<BundleEffect> Effects);
}
